const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const ctx = {window:{}, document:{hidden:false}, localStorage:{setItem(){}}, console};
vm.runInNewContext(fs.readFileSync('map-chat/frontend/js/plugin.js','utf8'),ctx);
const chat = new ctx.window.MeshPlugin();
chat.tracker = '!self'; chat.messages = {}; chat.deliveryUpdates = {}; chat.names = {0:'LongFast',1:'TAK'}; chat.active = 'ch:0'; chat.saved = {pins:[],unread:{},drafts:{}}; chat.panel = {classList:{contains:()=>false}};
chat.add({from_id:'!alice',to_id:'^all',channel_index:0,is_dm:false,text:'public',timestamp:1},true);
chat.add({from_id:'!alice',to_id:'!self',channel_index:0,is_dm:true,text:'private',timestamp:2},true);
chat.add({from_id:'!self',to_id:'!alice',channel_index:0,is_dm:true,text:'answer',timestamp:3},true);
assert.equal(chat.messages['ch:0'].length,1);
assert.equal(chat.messages['dm:!alice'].length,2);
assert.equal(chat.saved.unread['dm:!alice'],1);
chat.saved.pins.push('ch:0'); assert.equal(chat.keys()[0],'ch:0');
let request; chat.online=true; chat.pending=false; chat.active='ch:1'; chat.input={value:'hello'}; chat.api={messages:{sendTracked:(text,dest_id,channel_index,message_id)=>{request={text,dest_id,channel_index,message_id,delivery_tracking:true};return Promise.resolve({success:true});}}}; chat.status={}; chat.render=()=>{};
chat.sendMessage(); assert.equal(request.channel_index,1); assert.equal(request.dest_id,null); assert.equal(request.delivery_tracking,true);
const trackedId = request.message_id;
chat.updateDelivery(trackedId, 'delivered_mesh', 1);
chat.add({from_id:'!self',to_id:'^all',channel_index:1,is_dm:false,text:'hello',timestamp:3,message_id:trackedId,delivery_status:'submitted',delivery_revision:0},true);
assert.equal(chat.messages['ch:1'].length,1); assert.equal(chat.messages['ch:1'][0].delivery_status,'delivered_mesh');
chat.pending=false; chat.active='dm:!alice'; chat.sendMessage(); assert.equal(request.dest_id,'!alice');
chat.feed={scrollTop:3,scrollHeight:250}; chat.select('ch:0');
assert.equal(chat.saved.active,'ch:0'); assert.equal(chat.feed.scrollTop,250);
console.log('Conversation grouping, unread, pinning and send routing passed');
